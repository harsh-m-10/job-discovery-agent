#!/usr/bin/env python
"""Write dashboard/lib/settings.generated.ts from config/settings.yaml.

    python scripts/gen_dashboard_settings.py          # write
    python scripts/gen_dashboard_settings.py --check  # exit 1 if stale (CI)

docs/PLAN.md 8.2 (gap G6). The pipeline read its thresholds from
config/settings.yaml; the dashboard read the same numbers from Vercel
environment variables (PING_THRESHOLD, MAX_AGE_DAYS). They agreed by
convention only -- change one and the queue silently disagrees with the
pings. settings.yaml is now the only source: this script copies the values the
dashboard needs into a committed TypeScript module, and CI fails if the module
is out of date with the YAML.

Only display values are exported. Nothing private belongs in settings.yaml,
and the generated file is committed to a public repository.
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from common.settings import load_settings   # noqa: E402

OUT = ROOT / "dashboard" / "lib" / "settings.generated.ts"

# settings.yaml key -> exported constant, with the TS type of the value.
EXPORTS = {
    "ping_threshold": ("PING_THRESHOLD", "number"),
    "max_display_age_days": ("MAX_DISPLAY_AGE_DAYS", "number"),
}

# settings.yaml target_families.<key> -> exported string-array constant.
FAMILY_EXPORTS = {"core": "CORE_FAMILIES", "secondary": "SECONDARY_FAMILIES"}


def render() -> str:
    settings = load_settings()
    lines = [
        "// GENERATED by scripts/gen_dashboard_settings.py from config/settings.yaml.",
        "// Do not edit: change the YAML and re-run the script. CI fails if this",
        "// file is out of date (docs/PLAN.md 8.2).",
        "",
    ]
    for key, (const, ts_type) in EXPORTS.items():
        if key not in settings:
            sys.exit(f"config/settings.yaml has no {key!r}")
        value = settings[key]
        if ts_type == "number" and not isinstance(value, (int, float)):
            sys.exit(f"{key} must be a number, got {value!r}")
        lines.append(f"/** settings.yaml: {key} */")
        lines.append(f"export const {const}: {ts_type} = {value};")
    families = settings.get("target_families") or {}
    for key, const in FAMILY_EXPORTS.items():
        values = families.get(key)
        if not isinstance(values, list) or not all(isinstance(v, str) for v in values):
            sys.exit(f"target_families.{key} must be a list of family names")
        lines.append(f"/** settings.yaml: target_families.{key} */")
        lines.append(f"export const {const}: readonly string[] = {json.dumps(values)};")
    label = (settings.get("preferred_location") or {}).get("label")
    if not isinstance(label, str) or not label.strip():
        sys.exit("preferred_location.label must name the city")
    lines.append("/** settings.yaml: preferred_location.label (display only) */")
    lines.append(f"export const CITY_LABEL: string = {json.dumps(label.strip())};")
    return "\n".join(lines) + "\n"


def main() -> int:
    text = render()
    if "--check" in sys.argv:
        current = OUT.read_text(encoding="utf-8") if OUT.exists() else ""
        if current.replace("\r\n", "\n") != text:
            print(f"{OUT.relative_to(ROOT)} is stale -- run "
                  f"python scripts/gen_dashboard_settings.py", file=sys.stderr)
            return 1
        print("dashboard settings match config/settings.yaml")
        return 0
    OUT.write_text(text, encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
