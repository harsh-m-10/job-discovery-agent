#!/usr/bin/env python
"""Write seeds/companies.verified.yaml from the live, active roster.

    python scripts/export_roster.py

`python -m ingest.run --dry-run` and CI's ingestion smoke test read
seeds/companies.verified.yaml, because they run without database credentials.
That file used to be produced by scripts/verify_boards.py from
seeds/companies.yaml alone, so it drifted from what ingest actually polls: on
2026-10-15 it lacked batches 5 and 6 and still listed seven retired boards, and
verify_boards.py understands only three of the five ATSes.

The companies table is the source of truth for what is polled, so the file is
exported from it. Re-run after any roster change (adding a batch, retiring a
board); scripts/audit_roster.py and seeds/*.yaml record the reasons.
"""

from __future__ import annotations

import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from dotenv import load_dotenv   # noqa: E402
load_dotenv(ROOT / ".env")

from outcomes.run import Db      # noqa: E402

OUT = ROOT / "seeds" / "companies.verified.yaml"
HEADER = (
    "# Generated by scripts/export_roster.py from the live companies table\n"
    "# (active boards only) -- do not hand-edit. Read by ingest.run --dry-run and\n"
    "# CI's smoke test. Why each board is here, or was retired: seeds/*.yaml.\n"
)


def main() -> int:
    rows = Db().get_all("companies?select=name,ats,board_token,category,priority"
                        "&active=is.true&order=ats.asc,name.asc")
    entries = [{"name": r["name"], "ats": r["ats"], "token": r["board_token"],
                "category": r["category"], "priority": r["priority"]} for r in rows]
    OUT.write_text(HEADER + yaml.safe_dump(entries, sort_keys=False, allow_unicode=True),
                   encoding="utf-8")
    by_ats: dict[str, int] = {}
    for e in entries:
        by_ats[e["ats"]] = by_ats.get(e["ats"], 0) + 1
    print(f"wrote {len(entries)} active boards -> {OUT.relative_to(ROOT)}  {by_ats}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
